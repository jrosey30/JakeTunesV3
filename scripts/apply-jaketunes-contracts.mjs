#!/usr/bin/env node
/**
 * Apply vendor/jaketunes-contracts/contracts.json to generated desktop fences.
 *
 * Writes:
 *   src/main/sidecar-contracts.ts
 *   PHONE_PLAYLIST_SIDECARS in Dr. Claude/scripts/jaketunes-homemini-sync.sh
 *   PHONE_PLAYLIST_SIDECARS in Dr. Claude/scripts/jaketunes-workmini-deploy.sh
 *
 * Called by scripts/sync-jaketunes-contracts.sh after a fetch, or standalone
 * after a hand-edit of the vendored JSON (`node scripts/apply-jaketunes-contracts.mjs`).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const jsonPath = join(root, 'vendor/jaketunes-contracts/contracts.json')
const tsPath = join(root, 'src/main/sidecar-contracts.ts')
const bashFencePaths = [
  join(root, 'Dr. Claude/scripts/jaketunes-homemini-sync.sh'),
  join(root, 'Dr. Claude/scripts/jaketunes-workmini-deploy.sh'),
]

const contracts = JSON.parse(readFileSync(jsonPath, 'utf8'))
const sidecars = contracts.sidecars
if (!sidecars || typeof sidecars !== 'object') {
  throw new Error(`${jsonPath}: missing sidecars object`)
}
for (const key of ['desktopOwned', 'mobileWritable', 'phonePlaylistSidecarsNeverPushFromDesktop']) {
  if (!Array.isArray(sidecars[key]) || sidecars[key].some((x) => typeof x !== 'string')) {
    throw new Error(`${jsonPath}: sidecars.${key} must be a string[]`)
  }
}

const version = String(contracts.version || contracts.name || '0.1.0')
const notes = contracts.notes && typeof contracts.notes === 'object' ? contracts.notes : {}
const recoNote = typeof notes.recommendationsSingleWriter === 'string'
  ? notes.recommendationsSingleWriter
  : ''

function tsStringArray(name, values, extraIndent = '') {
  const inner = values.map((v) => `${extraIndent}  '${v}',`).join('\n')
  return `${extraIndent}export const ${name} = [\n${inner}\n${extraIndent}] as const`
}

function tsNotes(obj) {
  const entries = Object.entries(obj)
  if (entries.length === 0) {
    return 'export const notes = {} as const'
  }
  const inner = entries.map(([k, v]) => {
    const lit = JSON.stringify(v)
    return `  ${k}:\n    ${lit},`
  }).join('\n')
  return `export const notes = {\n${inner}\n} as const`
}

const ts = `/**
 * Sidecar write-identity lists from @jaketunes/contracts.
 *
 * Generated by scripts/apply-jaketunes-contracts.mjs from
 * vendor/jaketunes-contracts/contracts.json — do not hand-edit the lists.
 * Bump: npm run sync:contracts
 *
 * ⚠️ TWIN: vendor/jaketunes-contracts/contracts.json (and
 * https://github.com/jrosey30/jaketunes-contracts). Tests in
 * src/main/__tests__/phone-playlist-sidecars.test.ts lock both sides.
 */

export const JAKETUNES_CONTRACTS_VERSION = ${JSON.stringify(version)} as const

${tsStringArray('desktopOwned', sidecars.desktopOwned)}

${tsStringArray('mobileWritable', sidecars.mobileWritable)}

${tsStringArray('phonePlaylistSidecarsNeverPushFromDesktop', sidecars.phonePlaylistSidecarsNeverPushFromDesktop)}

export const sidecars = {
  desktopOwned,
  mobileWritable,
  phonePlaylistSidecarsNeverPushFromDesktop,
} as const

${tsNotes(notes)}

/** Companion aliases — same lists, matching the contracts package export style. */
export const DESKTOP_OWNED = desktopOwned
export const MOBILE_WRITABLE = mobileWritable
export const PHONE_PLAYLIST_SIDECARS_NEVER_PUSH_FROM_DESKTOP = phonePlaylistSidecarsNeverPushFromDesktop

const NEVER_BLUNT_PUSH = new Set<string>(phonePlaylistSidecarsNeverPushFromDesktop)

export function isNeverBluntPushFromDesktop(filename: string): boolean {
  return NEVER_BLUNT_PUSH.has(filename)
}

/**
 * Fail fast if a desktop push/reconcile list includes a phone-owned playlist
 * sidecar. Behavior-preserving vs current main: those names are already absent
 * from STATE_FILE_NAMES / SYNC_FILES; this makes putting them back a boot error.
 */
export function assertNoDesktopBluntPush(files: readonly string[], label: string): void {
  const hits = files.filter((f) => NEVER_BLUNT_PUSH.has(f))
  if (hits.length > 0) {
    throw new Error(
      \`[jaketunes-contracts] \${label} must not blunt-push \${hits.join(', ')} (sidecars.phonePlaylistSidecarsNeverPushFromDesktop)\`,
    )
  }
}

function assertContractInvariants(): void {
  for (const f of phonePlaylistSidecarsNeverPushFromDesktop) {
    if (!(mobileWritable as readonly string[]).includes(f)) {
      throw new Error(\`[jaketunes-contracts] \${f} is never-push-from-desktop but not in mobileWritable\`)
    }
    if ((desktopOwned as readonly string[]).includes(f)) {
      throw new Error(\`[jaketunes-contracts] \${f} cannot be both desktopOwned and never-push-from-desktop\`)
    }
  }
}
assertContractInvariants()
`

writeFileSync(tsPath, ts)
console.log(`wrote ${tsPath}`)

const bashArray = sidecars.phonePlaylistSidecarsNeverPushFromDesktop.join(' ')
const nextLine = `PHONE_PLAYLIST_SIDECARS=(${bashArray})`
for (const bashPath of bashFencePaths) {
  let syncSh = readFileSync(bashPath, 'utf8')
  if (!/PHONE_PLAYLIST_SIDECARS=\([^)]*\)/.test(syncSh)) {
    throw new Error(`${bashPath}: PHONE_PLAYLIST_SIDECARS=(...) assignment not found`)
  }
  syncSh = syncSh.replace(/PHONE_PLAYLIST_SIDECARS=\([^)]*\)/, nextLine)
  writeFileSync(bashPath, syncSh)
  console.log(`updated PHONE_PLAYLIST_SIDECARS in ${bashPath}`)
}

if (recoNote && !/recommendations\.json/.test(recoNote)) {
  console.warn('warning: notes.recommendationsSingleWriter does not mention recommendations.json')
}

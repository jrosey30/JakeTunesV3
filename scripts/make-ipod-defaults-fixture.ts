/**
 * Writes src/main/__tests__/fixtures/ipod-default-playlists.fixture.json: a
 * made-up library and iPod, and the default playlists the desktop's sync code
 * writes for it (renderer/utils/ipodDeviceDefaults.ts). Run once; the file is
 * then copied byte for byte to JakeTunesMobile
 * backend/src/util/__tests__/fixtures/, where homemini's twin must agree.
 *
 *   node --experimental-strip-types scripts/make-ipod-defaults-fixture.ts
 *
 * No song is from this year or later, so "Best of <year>" is empty in every
 * year and the file never goes stale. (Best of <year> has its own twin test.)
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ipodDefaultPlaylists } from '../src/renderer/utils/ipodDeviceDefaults.ts'
import type { Track } from '../src/renderer/types.ts'

let a = 20261114
const rnd = (): number => {
  a |= 0; a = (a + 0x6D2B79F5) | 0
  let t = Math.imul(a ^ (a >>> 15), 1 | a)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const pick = <T>(xs: readonly T[]): T => xs[Math.floor(rnd() * xs.length)]

// 12 of the 1960s, 30 of the 70s, 40 of the 80s, 32 of the 90s, 24 of the 2000s,
// 8 of the 2010s (under the 10 a decade needs), 4 of the 2020s, 10 with no year.
const decades: Array<[number, number]> = [[1960, 12], [1970, 30], [1980, 40], [1990, 32], [2000, 24], [2010, 8], [2020, 4], [0, 10]]
const library: Array<Partial<Track> & { id: number }> = []
let id = 1001
for (const [d, n] of decades) {
  for (let i = 0; i < n; i++) {
    const y = d === 0 ? pick(['', 0, 'unknown']) : d + Math.floor(rnd() * (d === 2020 ? 6 : 10))
    const artist = `Artist ${String.fromCharCode(65 + Math.floor(rnd() * 20))}`
    library.push({
      id: id++,
      title: `Song ${id}`,
      artist,
      albumArtist: artist,
      album: `Album ${Math.floor(rnd() * 40)}`,
      year: y as number,
      // Some under a minute: they never rank in Top 25.
      duration: rnd() < 0.08 ? 45_000 : 120_000 + Math.floor(rnd() * 240_000),
      // Ties on purpose: both sides must keep the list's order on a tie.
      playCount: rnd() < 0.2 ? 0 : Math.floor(rnd() * 30),
      rating: rnd() < 0.25 ? pick([20, 60, 100]) : 0,
      dateAdded: rnd() < 0.05 ? '' : new Date(Date.UTC(2015, 0, 1) + Math.floor(rnd() * 3000) * 86_400_000).toISOString(),
      lastPlayedAt: rnd() < 0.3 ? undefined : Date.UTC(2025, 0, 1) + Math.floor(rnd() * 600) * 3_600_000,
    })
  }
}
// The iPod: 150 of the 160 songs, in a shuffled list order, plus two ids the library doesn't have.
const ipodIds = library.map((t) => t.id).filter(() => rnd() < 0.94).sort(() => rnd() - 0.5)
ipodIds.splice(7, 0, 999_999)
ipodIds.push(888_888)
// Verified BPMs for most of the iPod's songs, and for one song that isn't on it.
const verifiedBpm: Record<string, number> = {}
for (const t of library) if (rnd() < 0.7) verifiedBpm[String(t.id)] = 50 + Math.floor(rnd() * 160) + (rnd() < 0.3 ? 0.5 : 0)

const expected = ipodDefaultPlaylists({
  library: library as Track[],
  ipodIds,
  setName: 'punkPod',
  original: false,
  verifiedBpm: new Map(Object.entries(verifiedBpm).map(([k, v]) => [Number(k), v])),
})

// The same songs as the Original: its Top 1000 is the one own list an iPod carries.
const asOriginal = ipodDefaultPlaylists({
  library: library as Track[],
  ipodIds,
  setName: 'Top 1000',
  original: true,
  verifiedBpm: new Map(Object.entries(verifiedBpm).map(([k, v]) => [Number(k), v])),
})

const out = {
  about: 'One iPod, its library and the default playlists the desktop’s sync writes for it. Generated by JakeTunesV3 scripts/make-ipod-defaults-fixture.ts; the same file, byte for byte, in JakeTunesMobile backend/src/util/__tests__/fixtures/.',
  setName: 'punkPod',
  ipodIds,
  verifiedBpm,
  library,
  expected,
  expectedAsOriginal: asOriginal,
}
const path = join(import.meta.dirname, '..', 'src', 'main', '__tests__', 'fixtures', 'ipod-default-playlists.fixture.json')
writeFileSync(path, JSON.stringify(out, null, 1) + '\n')
console.log(`wrote ${path}: ${expected.length} playlists — ${expected.map((p) => `${p.name} (${p.trackIds.length})`).join(', ')}`)
